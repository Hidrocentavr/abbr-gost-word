P('(ФГБОУ ВО «МГТУ «СТАНКИН»)', True)
P('УДК 621.865.8', indent=False)
P('ОТЧЕТ О НАУЧНО-ИССЛЕДОВАТЕЛЬСКОЙ РАБОТЕ', True)
P('Разработка системы управления роботизированной ячейкой механообработки (промежуточный)', True)
P('Москва 2026', True)

# --- реферат
