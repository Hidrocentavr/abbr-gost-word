P('1 ГОСТ 7.32-2017 СИБИД. Отчет о научно-исследовательской работе. Структура и правила оформления. — М.: Стандартинформ, 2017. — 32 с.')
P('2 Иванов И. И. Системы ЧПУ и ПЛК в машиностроении. — М.: Изд-во МГТУ им. Н. Э. Баумана, 2020. — 240 с.')

# --- приложение
