P('Отчет 24 с., 5 рис., 2 табл., 6 источн., 1 прил.')
P('РОБОТОТЕХНИЧЕСКИЙ КОМПЛЕКС, ПЛК, ЧПУ, ROS, СИСТЕМА УПРАВЛЕНИЯ, ТЕХНИЧЕСКОЕ ЗРЕНИЕ', indent=False)
P('Объектом исследования является РТК механообработки. Цель работы — разработка системы управления ячейкой на базе ПЛК и ROS.')

# --- содержание
H('СОДЕРЖАНИЕ')
for t in ['Перечень сокращений\t3', 'Введение\t4', '1 Анализ существующих решений\t5', 'Заключение\t8', 'Список использованных источников\t9', 'Приложение А\t10']:
    P(t, indent=False)

# --- перечень с ошибками
H('ПЕРЕЧЕНЬ СОКРАЩЕНИЙ')
for t in ['ЧПУ – числовое программное управление;',
          'ПЛК – программируемый логический контроллер',
          'АСУ – автоматизированная система управления',
          'ROS - Robot Operating System',
          'IOT – интернет вещей']:
    P(t, indent=False)

# --- введение
