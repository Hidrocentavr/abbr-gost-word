"""Тестовый отчёт о НИР с типовыми ошибками в сокращениях."""
import sys
from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK

out = sys.argv[1]
d = Document()
st = d.styles['Normal']
st.font.name = 'Times New Roman'; st.font.size = Pt(14)
st.paragraph_format.first_line_indent = Cm(1.25)
st.paragraph_format.line_spacing = 1.5
st.paragraph_format.space_after = Pt(0)
for s in d.sections:
    s.left_margin = Cm(3); s.right_margin = Cm(1.5); s.top_margin = Cm(2); s.bottom_margin = Cm(2)
h1 = d.styles['Heading 1']
h1.font.name = 'Times New Roman'; h1.font.size = Pt(14); h1.font.bold = True
h1.font.color.rgb = None
h1.paragraph_format.page_break_before = True
h1.paragraph_format.first_line_indent = Cm(0)

def P(text, center=False, indent=True):
    p = d.add_paragraph(text)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
    elif not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    return p

def H(text, center=True):
    p = d.add_heading(text, level=1)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p

